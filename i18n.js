const DICT = {}; EPT.forEach(r => { DICT[r[0].toLowerCase()] = r; });
const tr = s => { if (LANG === "en") return s; const k = String(s).trim().toLowerCase(); const r = DICT[k]; if (!r) return s;
  const i = { hi: 1, as: 2, bn: 3, ur: 4 }[LANG]; return r[i] || s; };

function translateTree(root) {
  if (LANG === "en" || !root) return;
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const jobs = []; let n; while ((n = walk.nextNode())) { const t = n.nodeValue.trim(); if (t.length > 1 && DICT[t.toLowerCase()]) jobs.push(n); }
  jobs.forEach(n => n.nodeValue = n.nodeValue.replace(n.nodeValue.trim(), tr(n.nodeValue.trim())));
  root.querySelectorAll("[placeholder]").forEach(e => { const p = e.getAttribute("placeholder"); if (DICT[p.trim().toLowerCase()]) e.setAttribute("placeholder", tr(p)); });
  root.querySelectorAll("option").forEach(o => { const t = o.textContent.trim(); if (DICT[t.toLowerCase()]) o.textContent = tr(t); });
  root.querySelectorAll("[title]").forEach(e => { const t = e.getAttribute("title"); if (DICT[t.trim().toLowerCase()]) e.setAttribute("title", tr(t)); });
}
function applyLang() {
  document.documentElement.lang = LANG;
  document.documentElement.dir = RTL.includes(LANG) ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", RTL.includes(LANG));
  translateTree(document.getElementById("content"));
  translateTree(document.getElementById("navLinks"));
  translateTree(document.getElementById("topbar") || document.body);
}
function setLang(l) {
  if (!LANGS[l]) l = "en";                            // never store a language we do not have
  LANG = l; localStorage.setItem("ep.lang", l);
  try { lang = l; } catch (e) { }
  applyDirection(l);
  location.reload();
}
function langPicker() {
  let sel = document.getElementById("langSel");
  if (!sel) { const host = document.querySelector("header.top") || document.body; sel = document.createElement("select"); sel.id = "langSel"; sel.className = "langsel"; host.appendChild(sel); }
  if (!sel.dataset.ready) {
    sel.innerHTML = Object.entries(LANGS).map(([k, v]) => `<option value="${k}" ${k === LANG ? "selected" : ""}>${v}</option>`).join("");
    sel.value = LANG; sel.dataset.ready = "1"; sel.onchange = () => setLang(sel.value);
    applyDirection(LANG);
  }
}
